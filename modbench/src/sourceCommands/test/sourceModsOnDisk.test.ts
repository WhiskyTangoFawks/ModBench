      const outcome = await build();

      expect(outcome).toMatchObject({ landed: [{ mod: 'Mod', trashed: ['mine.txt'] }], refused: [] });
      expect(inTrash).toEqual({ 'Mod.esp': 'my edit', 'mine.txt': 'mine' });
