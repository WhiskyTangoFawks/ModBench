import { afterEach, describe, expect, it, vi } from 'vitest';
import { execFileSync } from 'node:child_process';
import { mkdir, mkdtemp, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, relative } from 'node:path';
import { fakeVscodeModule } from '../../test/mo2/fakeVscodeWatcher';

vi.mock('vscode', () => fakeVscodeModule());

import { InMemoryMEditClient } from '../../client/test/InMemoryMEditClient';
import type { DecompileAndCommitMod } from '../../client';
import type { BuildMod } from '../../client/MEditClient';
import { fakeInstallationFileReader } from '../../test/fakeInstallationFileReader';
import { adapterOver } from '../../test/mo2/adapterOver';
import { recordingTasks } from '../../test/recordingTasks';
import { manifestText } from '../../manifestAdapter/manifestText';
import { sourceManifestIn, statusOf, type Manifest } from '../../manifestAdapter/manifestAdapter';
import { sourceCommands } from '../sourceCommands';

let root: string;

afterEach(() => rm(root, { recursive: true, force: true }));

async function put(path: string, text: string): Promise<void> {
  await mkdir(dirname(join(root, path)), { recursive: true });
  await writeFile(join(root, path), text);
}

async function textsBelow(folder: string): Promise<Record<string, string>> {
  const entries = await readdir(folder, { recursive: true, withFileTypes: true });
  const files = entries.filter((entry) => entry.isFile()).map((entry) => join(entry.parentPath, entry.name));
  return Object.fromEntries(await Promise.all(files.map(async (file) => [relative(folder, file).replaceAll('\\', '/'), await readFile(file, 'utf8')] as const)));
}

const PACK_ENTRIES = ['b.nif', 'textures/c.dds'];

async function aSourceModTakingFromAnInstallationFile(manifest: Partial<Manifest> = {}) {
  root = await mkdtemp(join(tmpdir(), 'modbench-source-mods-'));
  await put('ModOrganizer.ini', '[General]\r\ngameName=Fallout 4\r\nselected_profile=@ByteArray(Default)\r\n');
  await put('profiles/Default/modlist.txt', '# This file was automatically generated by Mod Organizer.\r\n+Mod\r\n');
  await put('downloads/Mod.7z', 'the downloaded file');
  await put('mods/Mod/meta.ini', '[General]\r\nversion=1.2\r\ninstallationFile=Mod.7z\r\n');
  await mkdir(join(root, 'source', 'Mod'), { recursive: true });
  execFileSync('git', ['init', '-q', join(root, 'source', 'Mod')]);
  const adapter = adapterOver(root, { installationFileReader: fakeInstallationFileReader(PACK_ENTRIES) });
  const pack = await adapter.downloadedFile('Mod.7z');
  if (pack.kind !== 'read' || pack.answer === undefined) throw new Error('no installation file');
  await put('source/Mod/Mod.manifest.json', manifestText({
    output: 'Mod', exclude: [], archives: [], steps: [], tools: [],
    packages: [{ kind: 'sourceRepository', name: 'Mod', isSubmodule: false }, { kind: 'installationFile', name: 'Mod.7z', size: pack.answer.size, hash: pack.answer.hash }],
    files: [{ path: 'b.nif', entry: { kind: 'held' }, package: 'Mod.7z' }, { path: 'textures/c.dds', entry: { kind: 'held' }, package: 'Mod.7z' }],
    ...manifest,
  }));
  const client = new InMemoryMEditClient();
  const sent: BuildMod[] = [];
  client.setCommandHandler('build', async (mods: readonly BuildMod[]) => {
    sent.push(...mods);
    await put('mods/Mod/Mod.esp', 'compiled');
    return { landed: [{ mod: 'Mod', compiled: [], refused: [], archivesRefused: [], overwritten: [], made: [{ path: 'Mod.esp', vouchedFor: true }] }], refused: [] };
  });
  const commands = sourceCommands({ client, adapter, saveUnsaved: () => Promise.resolve([]), tasks: recordingTasks() });
  const status = async () => statusOf({ name: 'Mod', folder: join(root, 'mods', 'Mod'), sourceFolder: join(root, 'source', 'Mod') }, adapter);
  const recorded = async (): Promise<Manifest | undefined> => {
    const read = await sourceManifestIn(join(root, 'source', 'Mod'));
    return read === undefined || 'refused' in read ? undefined : read.manifest;
  };
  return { build: () => commands.build(['Mod']), sent, status, recorded };
}

describe('build over an instance on disk', () => {
  it('writes the files its packages give before mEdit builds, records the manifest from what mEdit made, and reads its folder as its manifest says', async () => {
    const { build, sent, status, recorded } = await aSourceModTakingFromAnInstallationFile();

    const outcome = await build();

    expect(outcome).toEqual({ landed: [{ mod: 'Mod', compiled: [], refused: [], archivesRefused: [], overwritten: [] }], refused: [] });
    expect(sent).toMatchObject([{ taken: ['b.nif', 'textures/c.dds'] }]);
    expect(await textsBelow(join(root, 'mods', 'Mod'))).toEqual({
      'meta.ini': '[General]\r\nversion=1.2\r\ninstallationFile=Mod.7z\r\n', 'Mod.esp': 'compiled', 'b.nif': 'bytes of b.nif', 'textures/c.dds': 'bytes of textures/c.dds',
    });
    expect((await recorded())?.files).toEqual([
      { path: 'b.nif', entry: { kind: 'held' }, package: 'Mod.7z' }, { path: 'Mod.esp', entry: { kind: 'held' } },
      { path: 'textures/c.dds', entry: { kind: 'held' }, package: 'Mod.7z' },
    ]);
    expect((await recorded())?.version).toBe('1.2');
    expect(await status()).toMatchObject({ differing: [], namedByNoLine: [], gone: [], notInPackage: [], otherBytes: [] });
  });

  it('overwrites a file its package gives that holds other bytes, naming it, and leaves a file the build did not make', async () => {
    const { build, status } = await aSourceModTakingFromAnInstallationFile();
    await put('mods/Mod/b.nif', 'my edit');
    await put('mods/Mod/mine.txt', 'mine');

    const outcome = await build();

    expect(outcome).toMatchObject({ landed: [{ mod: 'Mod', overwritten: ['b.nif'] }] });
    expect(await readFile(join(root, 'mods', 'Mod', 'b.nif'), 'utf8')).toBe('bytes of b.nif');
    expect(await status()).toMatchObject({ differing: [], namedByNoLine: ['mine.txt'] });
  });

  it('writes a file its manifest excludes under the exclusion mark, its line naming it there and its path in its package', async () => {
    const { build, recorded } = await aSourceModTakingFromAnInstallationFile({ exclude: ['textures'] });

    await build();

    expect(await readFile(join(root, 'mods', 'Mod', 'textures.mohidden', 'c.dds'), 'utf8')).toBe('bytes of textures/c.dds');
    expect((await recorded())?.files).toContainEqual({ path: 'textures.mohidden/c.dds', entry: { kind: 'heldAt', path: 'textures/c.dds' }, package: 'Mod.7z' });
  });
});

describe('decompile and commit over an instance on disk', () => {
  async function aModWithItsManifest() {
    root = await mkdtemp(join(tmpdir(), 'modbench-init-'));
    await put('ModOrganizer.ini', '[General]\r\ngameName=Fallout 4\r\nselected_profile=@ByteArray(Default)\r\n');
    await put('profiles/Default/modlist.txt', '# This file was automatically generated by Mod Organizer.\r\n+Mod\r\n');
    await put('mods/Mod/meta.ini', '[General]\r\n');
    await put('mods/Mod/Mod.esp', 'plugin');
    await put('mods/Mod/a.nif', 'mine');
    await put('mods/Mod/Mod.manifest.json', manifestText({ packages: [], exclude: [], archives: [], steps: [], tools: [], files: [{ path: 'a.nif', entry: { kind: 'notHeld' } }] }));
    const client = new InMemoryMEditClient();
    const commands = sourceCommands({ client, adapter: adapterOver(root), saveUnsaved: () => Promise.resolve([]), tasks: recordingTasks() });
    return { client, decompileAndCommit: () => commands.decompileAndCommit(['Mod']) };
  }

  it('hands mEdit the repository with the manifest a build writes, and removes the manifest the mod folder held once it lands', async () => {
    const { client, decompileAndCommit } = await aModWithItsManifest();
    const handed: DecompileAndCommitMod[] = [];
    client.setCommandHandler('decompileAndCommit', (mods) => {
      handed.push(...mods);
      return Promise.resolve({ landed: [{ mod: 'Mod', plugins: [{ name: 'Mod.esp', origin: 'Mod' }] }], refused: [] });
    });

    const outcome = await decompileAndCommit();

    const [sent] = handed;
    expect(sent?.repository).toMatchObject({ sourceFolder: join(root, 'source', 'Mod'), assets: ['a.nif'], manifestName: 'Mod.manifest.json' });
    expect(outcome).toEqual({ landed: [{ mod: 'Mod', plugins: [{ name: 'Mod.esp', origin: 'Mod' }] }], refused: [] });
    expect(await readdir(join(root, 'mods', 'Mod'))).toEqual(['Mod.esp', 'a.nif', 'meta.ini']);
  });

  it('leaves the manifest the mod folder held when mEdit refuses the mod', async () => {
    const { client, decompileAndCommit } = await aModWithItsManifest();
    client.setCommandResult('decompileAndCommit', { landed: [], refused: [{ item: 'Mod', reason: 'it provides no plugin' }] });

    await decompileAndCommit();

    expect(await readdir(join(root, 'mods', 'Mod'))).toContain('Mod.manifest.json');
  });
});
