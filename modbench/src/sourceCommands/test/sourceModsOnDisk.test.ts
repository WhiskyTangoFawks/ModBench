describe('init source mod of a mod several downloaded files yield, over an instance on disk', () => {
  const YIELDS: Record<string, readonly string[]> = {
    'Alpha-100-1.zip': ['alpha.txt'], 'Beta-100-2.zip': ['beta.txt'], 'Gamma-200-1.zip': ['gamma.txt'], 'Delta-200-2.zip': ['delta.txt'],
  };
  const readerOfEachFile: InstallationFileReader = {
    list: (path) => Promise.resolve([...YIELDS[basename(path)] ?? []]),
    extract: async (path, destDir) => {
      for (const file of YIELDS[basename(path)] ?? []) await writeFile(join(destDir, file), `bytes of ${file}`);
    },
  };

  async function decompiled(installationFiles: string, folderFiles: readonly string[], notes: readonly string[] = []) {
    root = await mkdtemp(join(tmpdir(), 'modbench-several-'));
    await put('ModOrganizer.ini', '[General]\r\ngameName=Fallout 4\r\nselected_profile=@ByteArray(Default)\r\n');
    await put('profiles/Default/modlist.txt', '# This file was automatically generated by Mod Organizer.\r\n+Multi\r\n');
    await put('mods/Multi/meta.ini', `[General]\r\n${installationFiles}`);
    for (const file of folderFiles) await put(`mods/Multi/${file}`, file === 'own.txt' ? 'mine' : `bytes of ${file}`);
    for (const name of Object.keys(YIELDS)) await put(`downloads/${name}`, `the downloaded ${name}`);
    const client = new InMemoryMEditClient();
    const handed: ModToInitSourceMod[] = [];
    client.setCommandHandler('initSourceMod', (mods) => {
      handed.push(...mods);
      return Promise.resolve({ landed: [], refused: [] });
    });
    const adapter = adapterOver(root, { installationFileReader: readerOfEachFile });
    const noting = { ...adapter, downloadedFilesHashed: async () => ({ ...await adapter.downloadedFilesHashed(), notes }) };
    const outcome = await sourceCommands({ client, adapter: noting, saveUnsaved: () => Promise.resolve([]), tasks: recordingTasks(), trash: vi.fn() }).initSourceMod(['Multi'], { commit: true });
    const repository = handed[0]?.repository;
    const manifest = readManifest(repository?.manifest ?? '');
    assert('manifest' in manifest);
    return { outcome, assets: repository?.assets, packages: manifest.manifest.packages.map((pkg) => 'name' in pkg ? pkg.name : pkg.kind).sort(), yielded: pathsIn(manifest.manifest) };
  }

  it('commits as assets only the files no installation file of the mod yields, and names both packages, for a mod made from two installation files', async () => {
    const { assets, packages, yielded } = await decompiled('installationFile=Alpha-100-1.zip\r\n', ['alpha.txt', 'beta.txt', 'own.txt']);

    expect([assets, packages, yielded]).toEqual([['own.txt'], ['Alpha-100-1.zip', 'Beta-100-2.zip'], ['alpha.txt', 'beta.txt']]);
  });

  it('finds the package of a mod whose metadata names no installation file', async () => {
    const { assets, packages } = await decompiled('', ['delta.txt', 'own.txt']);

    expect([assets, packages]).toEqual([['own.txt'], ['Delta-200-2.zip']]);
  });

  it('hands mEdit the mod and answers the note of a downloaded file that could not be read whole, which leaves the packages right', async () => {
    const { outcome, assets } = await decompiled('', ['delta.txt', 'own.txt'], ['the hash index could not be written']);

    expect([assets, outcome]).toMatchObject([['own.txt'], { notes: ['the hash index could not be written'] }]);
  });
});
