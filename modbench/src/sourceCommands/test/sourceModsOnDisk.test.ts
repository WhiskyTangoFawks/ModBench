let root: string;

afterEach(() => rm(root, { recursive: true, force: true }));

async function put(path: string, text: string): Promise<void> {
  await mkdir(dirname(join(root, path)), { recursive: true });
  await writeFile(join(root, path), text);
}

async function textsBelow(folder: string): Promise<Record<string, string>> {
  const entries = await readdir(folder, { recursive: true, withFileTypes: true });
  const files = entries.filter((entry) => entry.isFile()).map((entry) => join(entry.parentPath, entry.name));
  return Object.fromEntries(await Promise.all(files.map(async (file) => [relative(folder, file).replaceAll('\\', '/'), await readFile(file, 'utf8')] as const)));
}

const PACK_ENTRIES = ['b.nif', 'textures/c.dds'];

const MADE = [{ path: 'Mod.esp', vouchedFor: true }];

async function aSourceModTakingFromAnInstallationFile(buildFile: Partial<BuildFile> = {}, made: readonly MadeFile[] = MADE, step = async () => {}) {
  root = await mkdtemp(join(tmpdir(), 'modbench-source-mods-'));
  await put('ModOrganizer.ini', '[General]\r\ngameName=Fallout 4\r\nselected_profile=@ByteArray(Default)\r\n');
  await put('profiles/Default/modlist.txt', '# This file was automatically generated by Mod Organizer.\r\n+Mod\r\n');
  await put('downloads/Mod.7z', 'the downloaded file');
  await put('mods/Mod/meta.ini', '[General]\r\nversion=1.2\r\ninstallationFile=Mod.7z\r\n');
  await mkdir(join(root, 'source', 'Mod'), { recursive: true });
  execFileSync('git', ['init', '-q', join(root, 'source', 'Mod')]);
  const adapter = adapterOver(root, { installationFileReader: fakeInstallationFileReader(PACK_ENTRIES) });
  const pack = await adapter.downloadedFile('Mod.7z');
  if (pack.kind !== 'read' || pack.answer === undefined) throw new Error('no installation file');
  await put(`source/Mod/${BUILD_FILE}`, manifestText({
    exclude: [], archives: [], tools: [],
    packages: [{ kind: 'installationFile', name: 'Mod.7z', size: pack.answer.size, hash: pack.answer.hash }],
    files: [{ path: 'b.nif', entry: { kind: 'held' } }, { path: 'textures/c.dds', entry: { kind: 'held' } }],
    ...buildFile,
  }));
  const client = new InMemoryMEditClient();
  const sent: BuildMod[] = [];
  client.setCommandHandler('build', async (mods: readonly BuildMod[]) => {
    sent.push(...mods);
    for (const { path } of made) await put(`mods/Mod/${path}`, 'built');
    return { landed: [{ mod: 'Mod', compiled: [], refused: [], archivesRefused: [], overwritten: [], made: [...made] }], refused: [] };
  });
  const tasks = recordingTasks(['Optimise']);
  const stepping = { ...tasks, whyStepsFailed: async (...ran: Parameters<typeof tasks.whyStepsFailed>) => { await step(); return tasks.whyStepsFailed(...ran); } };
  const commands = sourceCommands({ client, adapter, saveUnsaved: () => Promise.resolve([]), tasks: stepping });
  const status = async () => statusOf({ name: 'Mod', folder: join(root, 'mods', 'Mod') }, adapter);
  const recorded = async (): Promise<Manifest | undefined> => {
    const read = await manifestIn(join(root, 'mods', 'Mod'));
    return read === undefined || 'refused' in read ? undefined : read.manifest;
  };
  return { build: () => commands.build(['Mod']), sent, status, recorded, commands, adapter };
}

describe('build over an instance on disk', () => {
  it('writes the files its build file takes before mEdit builds, and leaves the build file as it was', async () => {
    const { build, sent } = await aSourceModTakingFromAnInstallationFile();
    const buildFile = await readFile(join(root, 'source', 'Mod', BUILD_FILE), 'utf8');

    const outcome = await build();

    expect(outcome).toEqual({ landed: [{ mod: 'Mod', compiled: [], refused: [], archivesRefused: [], overwritten: [] }], refused: [] });
    expect(sent).toMatchObject([{ taken: ['b.nif', 'textures/c.dds'] }]);
    expect(await textsBelow(join(root, 'mods', 'Mod'))).toEqual({
      'meta.ini': '[General]\r\nversion=1.2\r\ninstallationFile=Mod.7z\r\n', 'Mod.esp': 'built', 'b.nif': 'bytes of b.nif', 'textures/c.dds': 'bytes of textures/c.dds',
      'Mod.manifest.json': expect.any(String) as unknown,
    });
    expect([await readdir(join(root, 'source', 'Mod')), await readFile(join(root, 'source', 'Mod', BUILD_FILE), 'utf8')]).toEqual([['.git', BUILD_FILE], buildFile]);
  });

  it('records in the manifest in its folder its repository as its one package, with the mod\'s version, and each file the build made', async () => {
    const { build, status, recorded } = await aSourceModTakingFromAnInstallationFile();

    await build();

    expect(await recorded()).toEqual({
      packages: [{ kind: 'sourceRepository', name: 'Mod', isSubmodule: false }], version: '1.2', exclude: [], archives: [], tools: [],
      files: [{ path: 'b.nif', entry: { kind: 'held' } }, { path: 'Mod.esp', entry: { kind: 'held' } }, { path: 'textures/c.dds', entry: { kind: 'held' } }],
    });
    expect(await status()).toMatchObject({ differing: [], namedByNoLine: [], gone: [], notInPackage: [], otherBytes: [], noHost: true });
  });

  it('records each file a step makes that the folder holds, and reads it as the build made it', async () => {
    const { build, status, recorded } = await aSourceModTakingFromAnInstallationFile({
      steps: [{ task: 'Optimise', args: [] }], tools: [{ task: 'Optimise', page: 'https://example.com/o' }],
      files: [{ path: 'b.nif', entry: { kind: 'held' } }, { path: 'made.dds', entry: { kind: 'madeByStep' } }, { path: 'unmade.dds', entry: { kind: 'madeByStep' } }],
    }, MADE, async () => { await put('mods/Mod/made.dds', 'made'); });

    await build();

    expect((await recorded())?.files.map(({ path }) => path)).toEqual(['b.nif', 'made.dds', 'Mod.esp']);
    expect(await status()).toMatchObject({ differing: [], namedByNoLine: [], gone: [] });
  });

  it('overwrites a file its package gives that holds other bytes, naming it, and leaves a file the build did not make', async () => {
    const { build, status } = await aSourceModTakingFromAnInstallationFile();
    await put('mods/Mod/b.nif', 'my edit');
    await put('mods/Mod/mine.txt', 'mine');

    const outcome = await build();

    expect(outcome).toMatchObject({ landed: [{ mod: 'Mod', overwritten: ['b.nif'] }] });
    expect(await readFile(join(root, 'mods', 'Mod', 'b.nif'), 'utf8')).toBe('bytes of b.nif');
    expect(await status()).toMatchObject({ differing: [], namedByNoLine: ['mine.txt'] });
  });

  it('keeps the folder\'s exclusion: writes a file its packages give where the folder holds it under the mark, and reads its folder as its manifest says', async () => {
    const { build, status } = await aSourceModTakingFromAnInstallationFile();
    await put('mods/Mod/textures.mohidden/c.dds', 'old');

    await build();

    expect(await readFile(join(root, 'mods', 'Mod', 'textures.mohidden', 'c.dds'), 'utf8')).toBe('bytes of textures/c.dds');
    expect(await status()).toMatchObject({ differing: [], namedByNoLine: [], gone: [] });
  });
});

describe('build over an instance on disk, of a source mod renamed outside Modbench', () => {
  it('reads the manifest it holds under the name it had, builds where it is, and names the manifest for the folder (mods.md, Build, story 4)', async () => {
    const { build, sent, commands, adapter } = await aSourceModTakingFromAnInstallationFile();
    await build();
    const renamed = join(root, 'mods', 'Renamed');
    await rename(join(root, 'mods', 'Mod'), renamed);
    const before = { status: await statusOf({ name: 'Renamed', folder: renamed }, adapter), sourceMods: [...(await sourceModsOf((await adapter.modOrder()).modFolders, await adapter.sourceRepositories(), (name) => adapter.entryKey({ kind: 'mod', name }))).folders.keys()] };

    const outcome = await commands.build(['Renamed']);

    expect([before.status.noManifest, before.sourceMods]).toEqual([false, ['Renamed']]);
    expect(outcome).toMatchObject({ refused: [] });
    expect(sent.at(-1)).toMatchObject({ name: 'Renamed', sourceFolder: join(root, 'source', 'Mod'), folder: renamed });
    expect((await readdir(renamed)).filter((name) => name.endsWith('.manifest.json'))).toEqual(['Renamed.manifest.json']);
  });
});

describe('build over an instance on disk, of a file mEdit made that its source does not vouch for', () => {
  it('names it in the manifest, and reads it as differing from it', async () => {
    const { build, status, recorded } = await aSourceModTakingFromAnInstallationFile({}, [...MADE, { path: 'Mod - Main.ba2', vouchedFor: false }]);

    await build();

    expect((await recorded())?.files).toContainEqual({ path: 'Mod - Main.ba2', entry: { kind: 'held' } });
    expect(await status()).toMatchObject({ differing: ['Mod - Main.ba2'] });
  });
});

describe('decompile and commit over an instance on disk', () => {
  async function aModWithItsManifest(manifest: Partial<Manifest> = {}) {
    root = await mkdtemp(join(tmpdir(), 'modbench-init-'));
    await put('ModOrganizer.ini', '[General]\r\ngameName=Fallout 4\r\nselected_profile=@ByteArray(Default)\r\n');
    await put('profiles/Default/modlist.txt', '# This file was automatically generated by Mod Organizer.\r\n+Mod\r\n');
    await put('mods/Mod/meta.ini', '[General]\r\n');
    await put('mods/Mod/Mod.esp', 'plugin');
    await put('mods/Mod/a.nif', 'mine');
    await put('mods/Mod/Mod.manifest.json', manifestText({
      packages: [], exclude: [], archives: [], tools: [], files: [{ path: 'a.nif', entry: { kind: 'notHeld' } }], ...manifest,
    }));
    const client = new InMemoryMEditClient();
    const commands = sourceCommands({ client, adapter: adapterOver(root), saveUnsaved: () => Promise.resolve([]), tasks: recordingTasks() });
    return { client, decompileAndCommit: () => commands.decompileAndCommit(['Mod']) };
  }

  it('hands mEdit the repository with its build file, then names the repository in the manifest the mod folder holds, which its first build records', async () => {
    const { client, decompileAndCommit } = await aModWithItsManifest();
    const handed: DecompileAndCommitMod[] = [];
    client.setCommandHandler('decompileAndCommit', (mods) => {
      handed.push(...mods);
      return Promise.resolve({ landed: [{ mod: 'Mod', plugins: [{ name: 'Mod.esp', origin: 'Mod' }] }], refused: [] });
    });

    const outcome = await decompileAndCommit();

    const [sent] = handed;
    expect(sent?.repository).toMatchObject({ sourceFolder: join(root, 'source', 'Mod'), assets: ['a.nif'] });
    expect(outcome).toEqual({ landed: [{ mod: 'Mod', plugins: [{ name: 'Mod.esp', origin: 'Mod' }] }], refused: [] });
    expect(new Set(await readdir(join(root, 'mods', 'Mod')))).toEqual(new Set(['Mod.esp', 'Mod.manifest.json', 'a.nif', 'meta.ini']));
    expect(await manifestIn(join(root, 'mods', 'Mod'))).toMatchObject({ manifest: { packages: [{ kind: 'sourceRepository', name: 'Mod' }], files: [] } });
  });

  it('hands a file its manifest says a step made as an asset, as a build file holds the steps and a manifest holds none', async () => {
    const { client, decompileAndCommit } = await aModWithItsManifest({
      files: [{ path: 'a.nif', entry: { kind: 'notHeld' } }, { path: 'made.dds', entry: { kind: 'madeByStep' } }],
    });
    await put('mods/Mod/made.dds', 'made');
    const handed: DecompileAndCommitMod[] = [];
    client.setCommandHandler('decompileAndCommit', (mods) => { handed.push(...mods); return Promise.resolve({ landed: [], refused: [] }); });

    await decompileAndCommit();

    const [sent] = handed;
    const read = readBuildFile(sent?.repository.buildFile ?? '');
    expect([sent?.repository.assets, 'manifest' in read ? [read.manifest.steps, read.manifest.files] : read]).toEqual([['a.nif', 'made.dds'], [[], []]]);
  });

  it('refuses a mod whose folder\'s manifest names the game folder when the game folder was not found, handing mEdit nothing', async () => {
    const { client, decompileAndCommit } = await aModWithItsManifest({ packages: [{ kind: 'gameFolder', name: 'Fallout4', hash: 'AAAAAAAAAAA=', depots: [] }] });

    const outcome = await decompileAndCommit();

    expect([outcome, client.calls]).toEqual([
      { landed: [], refused: [{ item: 'Mod', reason: 'its manifest names the game folder, and the game folder was not found' }] }, [],
    ]);
  });
});
