import { afterEach, describe, expect, it, vi } from 'vitest';
import { InMemoryMEditClient } from '../../client/test/InMemoryMEditClient';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fakeVscodeModule } from '../../test/mo2/fakeVscodeWatcher';

vi.mock('vscode', () => fakeVscodeModule());

import { adapterOver } from '../../test/mo2/adapterOver';
import { fakeInstallationFileReader } from '../../test/fakeInstallationFileReader';
import { manifestIn } from '../../manifestAdapter/manifestFiles';
import { updateManifest } from '../updateManifest';
import { statusNow } from '../../test/statusNow';

let root: string;

afterEach(() => rm(root, { recursive: true, force: true }));

async function put(path: string, text: string): Promise<void> {
  await mkdir(dirname(join(root, path)), { recursive: true });
  await writeFile(join(root, path), text);
}

async function instanceTakingFromTheGame() {
  root = await mkdtemp(join(tmpdir(), 'modbench-update-manifest-'));
  await put('ModOrganizer.ini', '[General]\r\ngameName=Fallout 4\r\nselected_profile=@ByteArray(Default)\r\n');
  await put('profiles/Default/modlist.txt', '# This file was automatically generated by Mod Organizer.\r\n+Mod\r\n');
  await put('mods/Mod/a.nif', 'a');
  await put('mods/Mod/b.nif', 'b');
  await put('Game/Data/a.nif', 'a');
  await put('Game/Data/b.nif', 'b');
  const gameRoot = join(root, 'Game');
  const adapter = adapterOver(root, { gameFolder: { kind: 'found', root: gameRoot, dataFolder: join(gameRoot, 'Data') } });
  return { adapter, update: () => updateManifest({ adapter, client: new InMemoryMEditClient() }, ['Mod'], {}, [], false, []) };
}

describe('update manifest over an instance on disk', () => {
  it('writes the manifest of a mod whose files the game folder holds, naming the game folder as its package and each file with its hash', async () => {
    const { update } = await instanceTakingFromTheGame();

    await update();

    expect(await readFile(join(root, 'mods/Mod/Mod.manifest.json'), 'utf8')).toBe(
      '{\n"version":1,\n"packages":[\n{"kind":"gameFolder"}\n],\n"files":{\n"a.nif":"W26MqfHETtI=",\n"b.nif":"m5/zGqEqRXg="\n}\n}\n');
  });

  it('names no line for a metadata file of the mod', async () => {
    const { update } = await instanceTakingFromTheGame();
    await put('mods/Mod/meta.ini', 'what the mod manager holds');

    await update();

    expect(await readFile(join(root, 'mods/Mod/Mod.manifest.json'), 'utf8')).not.toContain('meta.ini');
  });

  it('leaves the mod it updated with no file differing from its game folder package', async () => {
    const { adapter, update } = await instanceTakingFromTheGame();
    await update();

    const status = await statusNow(adapter, { name: 'Mod', folder: join(root, 'mods', 'Mod') });

    expect([status.differing, status.namedByNoLine, status.gone]).toEqual([[], [], []]);
  });

  it('leaves it with none differing in the next session, which reads the hashes its manifest records', async () => {
    const { update } = await instanceTakingFromTheGame();
    await update();
    const next = adapterOver(root, { gameFolder: { kind: 'found', root: join(root, 'Game'), dataFolder: join(root, 'Game', 'Data') } });

    const status = await statusNow(next, { name: 'Mod', folder: join(root, 'mods', 'Mod') });

    expect(status.differing).toEqual([]);
  });
});

describe('update manifest over an instance on disk, of a mod whose metadata names no installation file', () => {
  async function aModTakingFromADownloadedFile() {
    root = await mkdtemp(join(tmpdir(), 'modbench-update-manifest-'));
    await put('ModOrganizer.ini', '[General]\r\ngameName=Fallout 4\r\nselected_profile=@ByteArray(Default)\r\n');
    await put('profiles/Default/modlist.txt', '# This file was automatically generated by Mod Organizer.\r\n+Mod\r\n');
    await put('downloads/Other.7z', 'another mod\'s downloaded file');
    await put('mods/Mod/meta.ini', '[General]\r\nversion=1.2\r\n');
    await put('mods/Mod/a.nif', 'bytes of a.nif');
    const adapter = adapterOver(root, { installationFileReader: fakeInstallationFileReader(['a.nif']) });
    await updateManifest({ adapter, client: new InMemoryMEditClient() }, ['Mod'], {}, [], false, []);
    const read = await manifestIn(join(root, 'mods', 'Mod'));
    if (read === undefined || 'refused' in read) throw new Error('no manifest');
    return { adapter, manifest: read.manifest };
  }

  it('names the downloaded file its files come from, which status reads as holding them (Never silently wrong)', async () => {
    const { adapter, manifest } = await aModTakingFromADownloadedFile();

    const status = await statusNow(adapter, { name: 'Mod', folder: join(root, 'mods', 'Mod') });

    expect([manifest.packages.map((pkg) => ('name' in pkg ? pkg.name : pkg.kind)), status.notInPackage, status.otherBytes]).toEqual([['Other.7z'], [], []]);
  });
});
