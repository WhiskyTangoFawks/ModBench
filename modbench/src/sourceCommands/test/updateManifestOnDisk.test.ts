import { afterEach, describe, expect, it, vi } from 'vitest';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileProblemsFake } from '../../test/fileProblemsFake';
import { fakeVscodeModule } from '../../test/mo2/fakeVscodeWatcher';

vi.mock('vscode', () => fakeVscodeModule());

import { adapterOver } from '../../test/mo2/adapterOver';
import { updateManifest } from '../updateManifest';
import { statusesNow } from '../../manifestAdapter/manifestAdapter';

let root: string;

afterEach(() => rm(root, { recursive: true, force: true }));

async function put(path: string, text: string): Promise<void> {
  await mkdir(dirname(join(root, path)), { recursive: true });
  await writeFile(join(root, path), text);
}

async function instanceTakingFromTheGame() {
  root = await mkdtemp(join(tmpdir(), 'modbench-update-manifest-'));
  await put('ModOrganizer.ini', '[General]\r\ngameName=Fallout 4\r\nselected_profile=@ByteArray(Default)\r\n');
  await put('profiles/Default/modlist.txt', '# This file was automatically generated by Mod Organizer.\r\n+Mod\r\n');
  await put('mods/Mod/a.nif', 'a');
  await put('mods/Mod/b.nif', 'b');
  await put('Game/Data/a.nif', 'a');
  await put('Game/Data/b.nif', 'b');
  const gameRoot = join(root, 'Game');
  const adapter = adapterOver(root, { gameFolder: { kind: 'found', root: gameRoot, dataFolder: join(gameRoot, 'Data') } });
  return { adapter, update: () => updateManifest({ adapter, pathProblems: fileProblemsFake(), instanceRoot: root }, ['Mod'], {}, [], false) };
}

describe('update manifest over an instance on disk', () => {
  it('writes the manifest of a mod whose files the game folder holds, naming the game folder as its package, pinned by the hash of the files it takes', async () => {
    const { update } = await instanceTakingFromTheGame();

    await update();

    expect(await readFile(join(root, 'mods/Mod/Mod.manifest.json'), 'utf8')).toBe(
      '{\n"packages": [\n{"gameFolder":"Fallout4","hash":"1z6VjVzj28w="}\n],\n"files": [\n{"path":"a.nif","packagePath":"Data/a.nif"},\n{"path":"b.nif","packagePath":"Data/b.nif"}\n]\n}\n');
  });

  it('leaves the mod it updated with no file differing from its game folder package', async () => {
    const { adapter, update } = await instanceTakingFromTheGame();
    await update();

    const [status] = await statusesNow(adapter, ['Mod']);

    expect([status?.differing, status?.namedByNoLine, status?.gone]).toEqual([[], [], []]);
  });

  it('leaves it with none differing in the next session, which reads the entries of the game folder package from the hash index', async () => {
    const { update } = await instanceTakingFromTheGame();
    await update();
    const next = adapterOver(root, { gameFolder: { kind: 'found', root: join(root, 'Game'), dataFolder: join(root, 'Game', 'Data') } });

    const [status] = await statusesNow(next, ['Mod']);

    expect(status?.differing).toEqual([]);
  });
});
