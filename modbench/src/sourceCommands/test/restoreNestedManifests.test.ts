import { afterEach, describe, expect, it, vi } from 'vitest';
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fakeVscodeModule } from '../../test/mo2/fakeVscodeWatcher';

vi.mock('vscode', () => fakeVscodeModule());

import { adapterOver } from '../../test/mo2/adapterOver';
import { InMemoryMEditClient } from '../../client/test/InMemoryMEditClient';
import { recordingTasks } from '../../test/recordingTasks';
import { modlistRepositoryCommands } from '../modlistRepositoryCommands';
import { hostGitRecordingInits } from './hostGitDouble';
import { nexusAnswering, answeringFrom } from '../../nexus/test/nexusDouble';

let root: string;

afterEach(async () => {
  await rm(root, { recursive: true, force: true });
});

async function put(path: string, text = 'x'): Promise<void> {
  await mkdir(dirname(join(root, path)), { recursive: true });
  await writeFile(join(root, path), text);
}

describe('restore from manifest over an instance on disk', () => {
  it('refuses the manifest of a folder and the manifest of the folder inside it, and sends mEdit neither', async () => {
    root = await mkdtemp(join(tmpdir(), 'modbench-restore-nested-'));
    await put('ModOrganizer.ini', '[General]\r\ngameName=Fallout 4\r\nselected_profile=@ByteArray(Default)\r\n');
    await put('profiles/Default/modlist.txt', '# This file was automatically generated by Mod Organizer.\r\n');
    await put('Stock Game/Stock Game.manifest.json');
    await put('Stock Game/Data/Data.manifest.json');
    const client = new InMemoryMEditClient();
    const adapter = adapterOver(root);
    const commands = modlistRepositoryCommands({
      client, adapter, nexus: nexusAnswering(answeringFrom({})).nexus, instanceRoot: root, hostGit: hostGitRecordingInits([]),
      trash: () => Promise.resolve(), tasks: recordingTasks(),
    });
    const { others } = await commands.otherManifests();

    const outcome = await commands.restoreFromManifest([], {}, true, others);

    expect([client.calls.filter(({ method }) => method === 'restoreFromManifest'), outcome]).toMatchObject([[], {
      applied: true,
      refused: [
        { item: 'Stock Game/', reason: "was skipped: its folder holds the folder of 'Stock Game/Data/'." },
        { item: 'Stock Game/Data/', reason: "was skipped: its folder is inside the folder of 'Stock Game/'." },
      ],
    }]);
  });
});
