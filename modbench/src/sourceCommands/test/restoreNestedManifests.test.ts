import { afterEach, describe, expect, it, vi } from 'vitest';
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fakeVscodeModule } from '../../test/mo2/fakeVscodeWatcher';

vi.mock('vscode', () => fakeVscodeModule());

import { adapterOver } from '../../test/mo2/adapterOver';
import { InMemoryMEditClient } from '../../client/test/InMemoryMEditClient';
import { recordingTasks } from '../../test/recordingTasks';
import { modlistRepositoryCommands } from '../modlistRepositoryCommands';
import { hostGitRecordingInits } from './hostGitDouble';
import { nexusAnswering, answeringFrom } from '../../nexus/test/nexusDouble';

let root: string;

afterEach(async () => {
  await rm(root, { recursive: true, force: true });
});

async function put(path: string, text = 'x'): Promise<void> {
  await mkdir(dirname(join(root, path)), { recursive: true });
  await writeFile(join(root, path), text);
}

async function instanceWithANestedPair() {
  root = await mkdtemp(join(tmpdir(), 'modbench-restore-nested-'));
  await put('ModOrganizer.ini', '[General]\r\ngameName=Fallout 4\r\nselected_profile=@ByteArray(Default)\r\n');
  await put('profiles/Default/modlist.txt', '# This file was automatically generated by Mod Organizer.\r\n');
  await Promise.all(['Stock Game/Stock Game.manifest.json', 'Stock Game/Data/Data.manifest.json', 'plugins/rb/rb.manifest.json'].map((path) => put(path)));
  const client = new InMemoryMEditClient();
  client.setCommandResult('restoreFromManifest', { landed: [], refused: [], notFound: [] });
  client.setCommandResult('updateManifest', { landed: [], refused: [] });
  const commands = modlistRepositoryCommands({
    client, adapter: adapterOver(root), nexus: nexusAnswering(answeringFrom({})).nexus, instanceRoot: root, hostGit: hostGitRecordingInits([]),
    trash: () => Promise.resolve(), tasks: recordingTasks(),
  });
  return { client, commands, found: await commands.otherManifests() };
}

const sentNames = (client: InMemoryMEditClient, method: 'restoreFromManifest' | 'updateManifest'): string[][] =>
  client.calls.filter((call) => call.method === method).map((call) => (call.args[0] as { name: string }[]).map(({ name }) => name));

describe('manifests outside mods/ over an instance on disk, one nested in the folder of another', () => {
  const NESTED = [
    { item: 'Stock Game/', reason: "was skipped: its folder holds the folder of 'Stock Game/Data/'." },
    { item: 'Stock Game/Data/', reason: "was skipped: its folder is inside the folder of 'Stock Game/'." },
  ];

  it('is refused by the search, both named, and the manifest beside them is the only one to act on', async () => {
    const { found } = await instanceWithANestedPair();

    expect([found.others.map(({ name }) => name), found.refused]).toEqual([['plugins/rb/'], NESTED]);
  });

  it('restores the manifest beside them and sends mEdit neither of the pair', async () => {
    const { client, commands, found } = await instanceWithANestedPair();

    await commands.restoreFromManifest([], {}, true, found.others);

    expect(sentNames(client, 'restoreFromManifest')).toEqual([['plugins/rb/']]);
  });

  it('updates the manifest beside them and sends mEdit neither of the pair', async () => {
    const { client, commands, found } = await instanceWithANestedPair();

    await commands.updateManifest([], {}, found.others);

    expect(sentNames(client, 'updateManifest')).toEqual([['plugins/rb/']]);
  });
});
