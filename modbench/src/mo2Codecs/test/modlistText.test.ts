const names = (text: string) => parseModlist(text).map((e) => e.name);

describe('insertSeparatorAtIndexInText', () => {
  it('inserts after the given entry index, preserving comment header, CRLF, and * lines', () => {
    const out = insertSeparatorAtIndexInText(defaultModlist(), 'New Sep', 0);
    expect(names(out)).toEqual([
      'SKK Fast Start new game (Fallout 4)',
      'New Sep',
      'Unassigned (Modlist Development)',
      '[NODELETE] Radfall',
      'Unofficial Fallout 4 Patch',
      'Radfall - All-In-One Survival Overhaul',
      'ENBoost - 12k',
      'Harder VATS',
      'Cracked and Smudged Pip-Boy Screen',
    ]);
    expect(out).toContain('+New Sep_separator\r\n');
    expect(out.startsWith('# This file was automatically generated by Mod Organizer.\r\n')).toBe(true);
    expect(out.endsWith('*Unmanaged: ccSBJFO4003-Grenade\r\n')).toBe(true);
  });

  it('inserts after the top entry without dropping or moving a leading BOM', () => {
    const out = insertSeparatorAtIndexInText('\uFEFF+First\r\n+Second\r\n', 'NewSep', 0);
    expect(out).toBe('\uFEFF+First\r\n+NewSep_separator\r\n+Second\r\n');
  });

  it('inserts after the last entry when afterIndex is at the end', () => {
    const out = insertSeparatorAtIndexInText(defaultModlist(), 'Tail Sep', 7);
    expect(names(out).at(-1)).toBe('Tail Sep');
    expect(out.endsWith('*Unmanaged: ccSBJFO4003-Grenade\r\n')).toBe(true);
  });

  it('clamps an out-of-range afterIndex to the last entry', () => {
    const out = insertSeparatorAtIndexInText(defaultModlist(), 'End Sep', 999);
    expect(names(out).at(-1)).toBe('End Sep');
  });

  it('new separator entry is parsed as a separator, not a mod', () => {
    const out = insertSeparatorAtIndexInText(defaultModlist(), 'My Group', 3);
    const entry = parseModlist(out).find((e) => e.name === 'My Group');
    expect(entry?.kind).toBe('separator');
  });

  it('inserts the first separator into a profile with no existing entries yet', () => {
    const out = insertSeparatorAtIndexInText('# header\n', 'FirstSep', 0);
    expect(out).toBe('# header\n+FirstSep_separator\n');
  });

  it('a file with both LF- and CRLF-terminated lines uses CRLF for the new line, not the first line\'s own LF (the shared detectEol\'s ruled whole-file-scan behavior, end to end through this caller)', () => {
    const out = insertSeparatorAtIndexInText('+A\n+B\r\n', 'Sep', 1);
    expect(out).toBe('+A\n+B\r\n+Sep_separator\r\n');
  });

  it('inserts before the first entry line when afterIndex is -1, leaving the comment header above it', () => {
    const out = insertSeparatorAtIndexInText(defaultModlist(), 'Winning Sep', -1);
    expect(names(out)[0]).toBe('Winning Sep');
    expect(out.startsWith(
      '# This file was automatically generated by Mod Organizer.\r\n+Winning Sep_separator\r\n+SKK Fast Start new game (Fallout 4)\r\n',
    )).toBe(true);
  });

  it('an empty modlist ignores -1 the same as any other index: the new separator is still the only entry', () => {
    const out = insertSeparatorAtIndexInText('# header\n', 'FirstSep', -1);
    expect(out).toBe('# header\n+FirstSep_separator\n');
  });
});

