const fixtureDir = join(__dirname, '..', '..', '..', 'test', 'mo2', 'fixtures', 'mo2-instance');
const defaultModlist = () =>
  readFileSync(join(fixtureDir, 'profiles', 'Default', 'modlist.txt'), 'utf8');

describe('setEnabledInText — byte-faithful surgical edit', () => {
  it('flips exactly one prefix and leaves every other byte (CRLF, comment, * lines) identical', () => {
    const input = defaultModlist();
    const out = setEnabledInText(input, 'SKK Fast Start new game (Fallout 4)', false);

    expect(out).toBe(input.replace('+SKK Fast Start new game (Fallout 4)', '-SKK Fast Start new game (Fallout 4)'));
    expect(out.length).toBe(input.length);
    expect(out).toContain('\r\n');
    expect(out).toContain('# This file was automatically generated by Mod Organizer.\r\n');
    expect(out).toContain('*DLC: Automatron\r\n');
  });

  it('is a no-op when the mod already has the requested state', () => {
    const input = defaultModlist();
    expect(setEnabledInText(input, 'SKK Fast Start new game (Fallout 4)', true)).toBe(input);
  });

  it('round-trips: disable then re-enable yields the original bytes', () => {
    const input = defaultModlist();
    const disabled = setEnabledInText(input, 'SKK Fast Start new game (Fallout 4)', false);
    expect(setEnabledInText(disabled, 'SKK Fast Start new game (Fallout 4)', true)).toBe(input);
  });

  it('throws when the mod name is not present', () => {
    expect(() => setEnabledInText(defaultModlist(), 'No Such Mod', false)).toThrow(/No Such Mod/);
  });

  it('does not match a separator line as a mod, so toggling a name that exists only as a separator fails', () => {
    expect(() => setEnabledInText(defaultModlist(), 'Unassigned (Modlist Development)', false)).toThrow();
  });

  it('preserves a leading BOM byte-for-byte when editing a later line', () => {
    const input = '\uFEFF+First\r\n+Second\r\n';
    const out = setEnabledInText(input, 'Second', false);
    expect(out).toBe('\uFEFF+First\r\n-Second\r\n');
  });
});

describe('entryNamed', () => {
  it('reads a separator\'s suffix off a line\'s or a folder\'s name, and anything else as a mod', () => {
    expect(entryNamed('Core_separator')).toEqual({ kind: 'separator', name: 'Core' });
    expect(entryNamed('Harder VATS')).toEqual({ kind: 'mod', name: 'Harder VATS' });
  });
});

describe('parseModlist', () => {
  it('surfaces mods and separators in priority order, ignoring comment/* /blank lines', () => {
    const entries = parseModlist(defaultModlist());
    expect(entries).toEqual([
      { kind: 'mod', name: 'SKK Fast Start new game (Fallout 4)', enabled: true },
      { kind: 'separator', name: 'Unassigned (Modlist Development)', enabled: false },
      { kind: 'mod', name: '[NODELETE] Radfall', enabled: true },
      { kind: 'mod', name: 'Unofficial Fallout 4 Patch', enabled: true },
      { kind: 'separator', name: 'Radfall - All-In-One Survival Overhaul', enabled: false },
      { kind: 'mod', name: 'ENBoost - 12k', enabled: true },
      { kind: 'mod', name: 'Harder VATS', enabled: false },
      { kind: 'mod', name: 'Cracked and Smudged Pip-Boy Screen', enabled: true },
    ] satisfies (Mod | Separator)[]);
  });

  it('recognizes an enabled separator (+…_separator)', () => {
    const entries = parseModlist('+ENB_separator\r\n');
    expect(entries).toEqual([{ kind: 'separator', name: 'ENB', enabled: true }]);
  });

  it('returns no entries for a file of only comment/* /blank lines', () => {
    expect(parseModlist('# header\r\n*DLC: Automatron\r\n\r\n')).toEqual([]);
  });

  it('strips a leading UTF-8 BOM so the top-priority mod is not silently dropped', () => {
    const entries = parseModlist('\uFEFF+First\r\n+Second\r\n');
    expect(entries).toEqual([
      { kind: 'mod', name: 'First', enabled: true },
      { kind: 'mod', name: 'Second', enabled: true },
    ] satisfies Mod[]);
  });

  it('does not surface a false entry when a BOM is followed by a non-entry line', () => {
    expect(parseModlist('\uFEFF# header\r\n*DLC: Automatron\r\n')).toEqual([]);
  });
});

const names = (text: string) => parseModlist(text).map((e) => e.name);

describe('insertSeparatorBesideInText', () => {
  const mod = (name: string) => ({ kind: 'mod', name }) as const;
  const separator = (name: string) => ({ kind: 'separator', name }) as const;

  it('matches the anchor and the repeated line without case, and counts only the first line of an entry', () => {
    const out = insertSeparatorBesideInText('+A\n+B\n-a\n+C\n+D\n', 'S', mod('c'));

    expect(out).toBe('+A\n+B\n-a\n+C\n+S_separator\n+D\n');
  });

  it('puts the separator directly after a mod, preserving comment header, CRLF, and * lines', () => {
    const out = insertSeparatorBesideInText(defaultModlist(), 'New Sep', mod('SKK Fast Start new game (Fallout 4)'));
    expect(names(out)).toEqual([
      'SKK Fast Start new game (Fallout 4)',
      'New Sep',
      'Unassigned (Modlist Development)',
      '[NODELETE] Radfall',
      'Unofficial Fallout 4 Patch',
      'Radfall - All-In-One Survival Overhaul',
      'ENBoost - 12k',
      'Harder VATS',
      'Cracked and Smudged Pip-Boy Screen',
    ]);
    expect(out).toContain('+New Sep_separator\r\n');
    expect(out.startsWith('# This file was automatically generated by Mod Organizer.\r\n')).toBe(true);
    expect(out.endsWith('*Unmanaged: ccSBJFO4003-Grenade\r\n')).toBe(true);
  });

  it('puts the separator after the last entry when the anchor is the last mod', () => {
    const out = insertSeparatorBesideInText(defaultModlist(), 'Tail Sep', mod('Cracked and Smudged Pip-Boy Screen'));
    expect(names(out).at(-1)).toBe('Tail Sep');
    expect(out.endsWith('*Unmanaged: ccSBJFO4003-Grenade\r\n')).toBe(true);
  });

  it('puts the separator before the first mod of a separator anchor\'s group, taking none', () => {
    const out = insertSeparatorBesideInText(defaultModlist(), 'Group Start', separator('Radfall - All-In-One Survival Overhaul'));
    expect(names(out).slice(1, 5)).toEqual(['Unassigned (Modlist Development)', 'Group Start', '[NODELETE] Radfall', 'Unofficial Fallout 4 Patch']);
  });

  it('puts the separator directly before an anchor separator with no mods of its own', () => {
    const out = insertSeparatorBesideInText('+First_separator\n+Second_separator\n+M\n', 'New', separator('Second'));
    expect(out).toBe('+First_separator\n+New_separator\n+Second_separator\n+M\n');
  });

  it('puts the separator before every mod when the anchor is the winning-most separator', () => {
    const out = insertSeparatorBesideInText(defaultModlist(), 'Winning Sep', separator('Unassigned (Modlist Development)'));
    expect(out.startsWith(
      '# This file was automatically generated by Mod Organizer.\r\n+Winning Sep_separator\r\n+SKK Fast Start new game (Fallout 4)\r\n',
    )).toBe(true);
  });

  it('anchors on the entry of the kind it is handed, when a mod and a separator share a name', () => {
    expect(insertSeparatorBesideInText('+Gear_separator\n+Gear\n', 'S', mod('Gear'))).toBe('+Gear_separator\n+Gear\n+S_separator\n');
  });

  it('new separator entry is parsed as a separator, not a mod', () => {
    const out = insertSeparatorBesideInText(defaultModlist(), 'My Group', mod('Harder VATS'));
    const entry = parseModlist(out).find((e) => e.name === 'My Group');
    expect(entry?.kind).toBe('separator');
  });

  it('inserts below an unterminated last entry without joining the two lines', () => {
    expect(insertSeparatorBesideInText('+A', 'S', mod('A'))).toBe('+A\n+S_separator');
  });

  it('refuses an anchor the order does not list', () => {
    expect(() => insertSeparatorBesideInText('+A\n', 'S', mod('B'))).toThrow('B is not in the modlist');
  });
});

